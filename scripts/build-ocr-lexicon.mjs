// Builds src/data/ocrLexicon.js — the word list the OCR legibility heuristic
// (src/import/legibility.js) checks recognised words against. Sources: the
// repo's own ingredient/unit/modifier data plus a short list of everyday
// recipe-prose words. Re-run after changing the ingredient data:
//   node scripts/build-ocr-lexicon.mjs
import fs from 'node:fs';
const sources = [
  'src/data/ingredients', 'src/data/pantry/ingredientCatalog.js',
  'src/data/bar/ingredientCatalog.js', 'src/utils/ingredientEntities.js',
];
let text = '';
for (const src of sources) {
  const st = fs.statSync(src);
  if (st.isDirectory()) for (const n of fs.readdirSync(src)) text += fs.readFileSync(`${src}/${n}`, 'utf8');
  else text += fs.readFileSync(src, 'utf8');
}
const PROSE = `the and with for from into onto over until then when while each every all any some more less
about after before again also always add added adding bake baked baking beat beaten blend boil boiled bowl
bring brown browned butter chill chop chopped combine cook cooked cool cooled cover covered cream cut dice
diced dish divide drain drop dry evenly fold fry gently golden grease greased heat heated hot inch inches
large layer let line lined low medium melt melted minced minute minutes mix mixed mixing mixture oven pan
paper pieces place pour preheat prepare recipe remove rest roll room serve served serves set side simmer
slice sliced slowly small soft spoon spread sprinkle square stir stirred strain sugar taste temperature
thick thin through top transfer turn until warm water well whisk whisked wide add ingredients method notes
directions instructions step steps degrees hour hours sheet tray paper parchment wax cake cookies cookie
bread soup salad sauce dressing toss uncooked unbeaten optional finely roughly crushed shredded grated
sifted real fresh frozen canned leftover handful pinch dash cup cups tablespoon tablespoons teaspoon
teaspoons tsp tbsp gram grams ounce ounces pound pounds stick sticks clove cloves can cans min mins hrs`;
const words = new Set(text.toLowerCase().match(/[a-z]{3,}/g) || []);
// Drop code noise picked up from the .js sources (before PROSE, so real
// recipe words like "let" survive).
for (const w of ['const', 'export', 'default', 'function', 'return', 'import', 'null', 'true', 'false', 'undefined', 'var', 'let']) words.delete(w);
for (const w of PROSE.split(/\s+/)) if (w) words.add(w);
const list = [...words].sort();
fs.writeFileSync('src/data/ocrLexicon.js',
  '// GENERATED by scripts/build-ocr-lexicon.mjs — do not edit by hand.\n'
  + '// Words the OCR legibility heuristic counts as "real" (src/import/legibility.js).\n'
  + `export default ${JSON.stringify(list.join(' '))};\n`);
console.log(`${list.length} words, ${fs.statSync('src/data/ocrLexicon.js').size} bytes`);
